import type { NextConfig } from "next";

// Deny-by-default security headers for the public site. The public site loads
// nothing from other origins and is never embedded, so the policy has no
// third-party allowances.
//
// script-src/style-src 'unsafe-inline': Next.js's App Router injects inline
// hydration bootstrap scripts on every page, so 'script-src self' alone
// breaks hydration. A nonce-based CSP is the documented alternative but needs
// per-request nonce plumbing through src/proxy.ts; the site has no
// user-generated HTML, and React's JSX escaping covers the realistic
// injection vector. 'unsafe-eval' is development-only (React's dev tooling).
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${process.env.NODE_ENV === "production" ? "" : " 'unsafe-eval'"}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), payment=(), usb=()",
  },
  ...(process.env.NODE_ENV === "production"
    ? [
        {
          key: "Strict-Transport-Security",
          value: "max-age=63072000; includeSubDomains; preload",
        },
      ]
    : []),
];

const nextConfig: NextConfig = {
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
